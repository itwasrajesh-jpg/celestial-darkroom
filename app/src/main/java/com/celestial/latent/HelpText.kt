package com.celestial.latent

/**
 * App help (74a): what every darkroom control does, tab by tab, with when to reach for it.
 *
 * Written from the code, not guessed: ranges are the sliders' own, and where a control's direction
 * depends on the film or the phone (the colour filters) the text says so rather than promising one.
 * Kept apart from the screens so the words can be corrected without touching any layout.
 */
object HelpText {
    class Item(
        val name: String,
        val range: String,
        val what: String,
        val lower: String = "",
        val higher: String = "",
        val use: String = "",
        val lowLabel: String = "LOWER",
        val highLabel: String = "HIGHER",
    )

    class Section(val title: String, val intro: String = "", val items: List<Item> = emptyList())

    /** A diffusion filter, drawn as a light with its glow: sizes in dp at a 1:1 drawing, [floor] the ground's lift. */
    class Filter(
        val id: String, val label: String, val tag: String, val what: String, val use: String,
        val core: Float, val halo: Float, val bloom: Float, val tint: Long, val floor: Long,
    )

    class Topic(
        val id: String,
        val title: String,
        val group: String,
        val sub: String,
        val intro: String,
        val sections: List<Section>,
        val filters: List<Filter> = emptyList(),
    )

    private fun onOff(name: String, what: String, off: String, on: String, use: String) =
        Item(name, "on / off", what, off, on, use, lowLabel = "OFF", highLabel = "ON")

